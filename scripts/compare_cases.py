"""Reproducible keyword-vs-purpose comparison for the problem-5 cases (no network, no model call).

    python scripts/compare_cases.py        # writes evidence/q05_cases.md and evidence/q05_cases.json

Data: committed real snapshot (data/snapshots) + manually verified case records
(tests/fixtures/cases/manual_cases.py), evaluated at the fixed TEST time in that file.
This compares two ways of handling the SAME candidates inside this app. It says nothing about
external products and nothing about user outcomes.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

REPO_DIR = Path(__file__).resolve().parents[1]
if str(REPO_DIR) not in sys.path:
    sys.path.insert(0, str(REPO_DIR))

from tests.fixtures.cases.manual_cases import CASE_NOW  # noqa: E402
from tests.fixtures.cases.specs import CASES, case_session, run_case  # noqa: E402

LABEL = {"match": "match", "conditional": "conditional (check first)", "excluded": "excluded"}


def main() -> int:
    sys.stdout.reconfigure(encoding="utf-8")
    s = case_session()
    results = [run_case(c, s) for c in CASES]
    (REPO_DIR / "evidence" / "q05_cases.json").write_text(json.dumps(results, ensure_ascii=False, indent=2), encoding="utf-8")

    lines = [
        "# Problem 5: keyword/tag list vs purpose- and condition-aware handling",
        "",
        f"Generated by `python scripts/compare_cases.py`. Fixed TEST time: {CASE_NOW.isoformat()} (America/New_York).",
        "Data: committed real snapshot + 3 manually verified case records (sports leagues, camera club).",
        "Structured profiles are hand-written readings of each request (the model's own reading is checked in real runs).",
        "This is an internal comparison of two treatments of the same candidates; it is not evidence about external products or user outcomes.",
        "",
        "| Case | Request | Keyword/tag list | Purpose-aware: match / conditional / excluded |",
        "|---|---|---|---|",
    ]
    for r in results:
        c = r["counts"]
        lines.append(f"| {r['case']} | {r['request']} | {len(r['baseline'])} shown, all as results | "
                     f"{c['match']} / {c['conditional']} / {c['excluded']} |")
    for r in results:
        lines += ["", f"## {r['case']}: {r['title']}", "", f"Request: “{r['request']}”", ""]
        if not r["rows"]:
            lines.append("No listing contains any of the tags; both treatments return nothing (honest empty result).")
            continue
        lines += ["| Listing | Kind | Status | Why (from the page vs. what the user said) | Interaction words on the page |",
                  "|---|---|---|---|---|"]
        for row in r["rows"]:
            why = "; ".join(row["reasons"]) if row["status"] == "excluded" else (
                "To confirm: " + " ".join(row["to_confirm"]) if row["to_confirm"] else "No open hard condition. " + " ".join(row["met"]))
            lines.append(f"| {row['title']} | {row['kind']} | {LABEL[row['status']]} | {why.replace('|', '/')} | {row['interaction'] or 'none found'} |")
    out = REPO_DIR / "evidence" / "q05_cases.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out.relative_to(REPO_DIR)} and evidence/q05_cases.json")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
